"""Exercise only the spawned Qt fixture through an explicitly selected helper."""
import argparse
import ctypes
import json
import subprocess
import sys
import threading
import time
import uuid
from pathlib import Path
from native_client import Bridge

sys.coinit_flags = 0
import comtypes.client  # noqa: E402 - COM apartment must be configured before import.

parser = argparse.ArgumentParser()
parser.add_argument('--helper', type=Path, required=True)
parser.add_argument('--fixture-python', type=Path, required=True)
parser.add_argument('--output', type=Path, required=True)
parser.add_argument('--baseline', action='store_true')
parser.add_argument('--window-root', action='store_true')
args = parser.parse_args()
args.output.mkdir(parents=True, exist_ok=True)
user32 = ctypes.WinDLL('user32', use_last_error=True)
user32.GetForegroundWindow.restype = ctypes.c_void_p
user32.SetThreadDpiAwarenessContext.argtypes = [ctypes.c_void_p]
user32.SetThreadDpiAwarenessContext.restype = ctypes.c_void_p
user32.SetThreadDpiAwarenessContext(ctypes.c_void_p(-4))
user32.SetForegroundWindow.argtypes = [ctypes.c_void_p]
user32.IsWindow.argtypes = [ctypes.c_void_p]
user32.SetWindowPos.argtypes = [ctypes.c_void_p, ctypes.c_void_p, ctypes.c_int, ctypes.c_int,
                             ctypes.c_int, ctypes.c_int, ctypes.c_uint]
user32.GetWindowThreadProcessId.argtypes = [ctypes.c_void_p, ctypes.POINTER(ctypes.c_uint)]
user32.GetAncestor.argtypes = [ctypes.c_void_p, ctypes.c_uint]
user32.GetAncestor.restype = ctypes.c_void_p
comtypes.client.GetModule('UIAutomationCore.dll')
from comtypes.gen import UIAutomationClient as U  # noqa: E402 - Generated by GetModule above.
user32.WindowFromPoint.argtypes = [U.tagPOINT]
user32.WindowFromPoint.restype = ctypes.c_void_p
user32.GetWindowRect.argtypes = [ctypes.c_void_p, ctypes.POINTER(U.tagRECT)]
uia = comtypes.client.CreateObject(U.CUIAutomation, interface=U.IUIAutomation)
previous_foreground = user32.GetForegroundWindow()
results = []


def wait_until(predicate, seconds=12):
    deadline = time.monotonic() + seconds
    while time.monotonic() < deadline:
        value = predicate()
        if value:
            return value
        time.sleep(0.03)
    raise TimeoutError('fixture condition did not arrive')


def state():
    path = args.output / 'state.jsonl'
    if not path.exists():
        return None
    complete = path.read_bytes().rpartition(b'\n')[0]
    return json.loads(complete.splitlines()[-1].decode('utf-8')) if complete else None


def command(operation):
    name = f'command-{time.time_ns()}.json'
    path = args.output / name
    path.write_text(json.dumps({'operation': operation}), encoding='utf-8')
    wait_until(lambda: state()['lastCommand'] == name)


def ok(reply):
    assert reply.get('ok'), reply
    return reply['result']


def nodes(root):
    yield root
    for child in root.get('children', []):
        yield from nodes(child)


fixture_log = (args.output / 'fixture.log').open('w', encoding='utf-8')
nonce = uuid.uuid4().hex
fixture = subprocess.Popen([str(args.fixture_python.resolve()),
    str(Path(__file__).with_name('qt-fixture.py').resolve()), '--state-dir', str(args.output.resolve()),
    '--nonce', nonce],
    stdout=fixture_log, stderr=fixture_log)
bridge = None
focus_changes = []
monitor_running = True

def monitor_focus():
    previous = None
    while monitor_running:
        current = user32.GetForegroundWindow()
        if current != previous:
            focus_changes.append({'time': time.monotonic(), 'hwnd': current})
            previous = current
        time.sleep(0.002)

threading.Thread(target=monitor_focus, daemon=True).start()
try:
    fixture_state = wait_until(lambda: state() if state() and state().get('nonce') == nonce else None)
    hwnd = fixture_state['hwnd']
    fixture_pid = fixture_state['pid']
    pid = ctypes.c_uint()
    user32.GetWindowThreadProcessId(hwnd, ctypes.byref(pid))
    assert pid.value == fixture_pid and (fixture_pid == fixture.pid or fixture_state['parentPid'] == fixture.pid), 'must target the spawned fixture only'
    bridge = Bridge(args.helper, args.output)

    def activate_fixture():
        user32.SetForegroundWindow(hwnd)
        if user32.GetForegroundWindow() == hwnd:
            return
        user32.SetWindowPos(hwnd, ctypes.c_void_p(0), 0, 0, 0, 0, 0x0013)
        bounds = U.tagRECT()
        user32.GetWindowRect(hwnd, ctypes.byref(bounds))
        point = U.tagPOINT(bounds.left + 120, bounds.top + 16)
        hit = user32.WindowFromPoint(point)
        assert user32.GetAncestor(hit, 2) == hwnd, 'neutral caption must belong to the fixture'
        user32.SetCursorPos(point.x, point.y)
        user32.mouse_event(0x0002, 0, 0, 0, 0)
        user32.mouse_event(0x0004, 0, 0, 0, 0)
        wait_until(lambda: user32.GetForegroundWindow() == hwnd)

    def look(include_image=False):
        return ok(bridge.call('look', {'windowId': hwnd, 'includeImage': include_image, 'readText': 'never'}))

    def named(look_result, title):
        return [node for node in nodes(look_result['outline']) if node.get('title') == title]

    def act(look_result, target, action='press', parameters=None):
        return bridge.call('act', {'lookId': look_result['lookId'], 'pid': fixture_pid,
            'target': {'ref': target['ref']}, 'action': action,
            'policy': 'foreground', 'params': parameters or {}, 'deferRootDelta': True})

    observed = look()
    reads = []
    for title in ['按钮A', '同名按钮', '按钮B']:
        for node in named(observed, title):
            reply = bridge.call('uiaReadText', {'lookId': observed['lookId'], 'elementRef': node['ref'], 'limit': 256})
            text = reply.get('result', {}).get('text')
            reads.append({'expected': title, 'actual': text, 'ok': text == title})
    assert len(reads) == 4, reads
    results.append({'case': 'four distinct references read their own labels', 'reads': reads,
                    'passed': all(item['ok'] for item in reads)})
    if args.baseline:
        assert not results[-1]['passed'], 'baseline must reproduce the wrong-reference defect'
    else:
        assert results[-1]['passed'], results[-1]
        same = sorted(named(observed, '同名按钮'), key=lambda node: node['rect']['y'])
        for key, node in [('same_left', same[0]), ('same_right', same[1])]:
            before = state()['counts'].copy()
            ok(act(observed, node))
            wait_until(lambda: state()['counts'][key] == before[key] + 1)
            after = state()['counts']
            assert all(after[k] == value + (k == key) for k, value in before.items()), after
        results.append({'case': 'same-name buttons change only their own counters', 'passed': True})

        activate_fixture()
        current = look()
        inputs = [node for node in nodes(current['outline']) if node.get('role') == 'edit']
        inputs.sort(key=lambda node: node['rect']['y'])
        assert len(inputs) == 2, inputs
        for index, node in enumerate(inputs):
            ok(act(current, node, 'setText', {'text': f'candidate-{index + 1}'}))
            wait_until(lambda: state()['texts'][index] == f'candidate-{index + 1}')
        assert state()['texts'] == ['candidate-1', 'candidate-2']
        results.append({'case': 'two edit references write separate fields', 'passed': True})

        current = look(include_image=True)
        combo_nodes = [node for node in nodes(current['outline']) if node.get('role') == 'comboBox']
        assert len(combo_nodes) == 1, combo_nodes
        combo_node = combo_nodes[0]
        rect = combo_node['rect']
        ok(bridge.call('act', {'lookId': current['lookId'], 'pid': fixture_state['pid'],
            'target': {'x': rect['x'] + rect['w'] / 2,
                       'y': rect['y'] + rect['h'] / 2},
            'action': 'click', 'policy': 'foreground', 'params': {}, 'deferRootDelta': True}))
        opened = look()
        option = named(opened, 'RAW16+YUV')[0]
        assert option['role'].lower() == 'listitem', option
        # Commit the observed list choice through the focused popup. The selected
        # view row resets after activation; only the actual combo value is an outcome.
        selected_text = ok(bridge.call('uiaReadText', {'lookId': opened['lookId'], 'elementRef': option['ref']}))
        assert selected_text['text'] == 'RAW16+YUV', selected_text
        window_node = next(node for node in nodes(opened['outline']) if node.get('role') == 'window')
        ok(act(opened, window_node, 'keypress', {'keys': ['HOME']}))
        ok(act(opened, window_node, 'keypress', {'keys': ['DOWN']}))
        ok(act(opened, window_node, 'keypress', {'keys': ['ENTER']}))
        wait_until(lambda: state()['combo'] == 'RAW16+YUV')
        command('close_combo')
        results.append({'case': 'combo opens through observed coordinates, exposes list-item references and commits keyboard selection', 'passed': True})

        stale_look = look()
        stale_b = named(stale_look, '按钮B')[0]
        command('remove_b')
        time.sleep(0.15)
        before = state()['counts'].copy()
        stale_reply = act(stale_look, stale_b)
        assert not stale_reply.get('ok'), stale_reply
        assert state()['counts'] == before
        results.append({'case': 'destroyed widget reference cannot operate another widget',
                        'passed': True, 'reply': stale_reply})

        # Physical input is confined to this disposable fixture.
        activate_fixture()
        canvas_look = look()
        canvas_node = named(canvas_look, '物理点击画布')[0]
        before = state()['counts']['canvas']
        ok(act(canvas_look, canvas_node))
        wait_until(lambda: state()['counts']['canvas'] == before + 1)
        command('show_overlay')
        time.sleep(0.15)
        covered_look = look()
        covered_node = named(covered_look, '物理点击画布')[0]
        before = state()['counts'].copy()
        covered = act(covered_look, covered_node)
        assert not covered.get('ok') and 'occluded' in covered['error']['message'].lower(), covered
        assert state()['counts'] == before
        results.append({'case': 'physical fallback works uncovered and rejects real occlusion',
                        'passed': True, 'reply': covered})
        command('hide_overlay')

        if args.window_root:
            activate_fixture()
            root_look = look()
            root_node = root_look['outline']
            blocked = bridge.call('act', {'lookId': root_look['lookId'], 'pid': fixture_pid,
                'target': {'ref': root_node['ref']}, 'action': 'keypress',
                'policy': 'ax_only', 'params': {'keys': ['F6']}, 'deferRootDelta': True})
            assert not blocked.get('ok') and blocked['error']['code'] == 'coordinate_blocked', blocked
            results.append({'case': 'outer window root still rejects background raw keyboard input',
                            'passed': True, 'reply': blocked})
            ok(act(root_look, root_node, 'keypress', {'keys': ['ALT', 'F4']}))
            wait_until(lambda: not user32.IsWindow(hwnd))
            fixture.wait(timeout=5)
            results.append({'case': 'outer window root ALT+F4 closes only the owned fixture',
                            'passed': True, 'windowClosed': True})

    (args.output / 'result.json').write_text(json.dumps({'baseline': args.baseline,
        'helper': str(args.helper.resolve()), 'fixturePid': fixture_pid, 'cases': results},
        ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({'baseline': args.baseline, 'cases': results}, ensure_ascii=False, indent=2))
except Exception:
    (args.output / 'failure-state.json').write_text(json.dumps({
        'state': state(), 'foreground': user32.GetForegroundWindow(),
        'fixtureExitCode': fixture.poll(),
        'fixtureWindowExists': bool(user32.IsWindow((state() or {}).get('hwnd', 0))),
        'focusChanges': focus_changes}, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    raise
finally:
    monitor_running = False
    if bridge:
        bridge.close()
    foreground_pid = ctypes.c_uint()
    user32.GetWindowThreadProcessId(user32.GetForegroundWindow(), ctypes.byref(foreground_pid))
    restore_foreground = foreground_pid.value == (state() or {}).get('pid')
    if fixture.poll() is None:
        (args.output / f'command-{time.time_ns()}.json').write_text(
            json.dumps({'operation': 'quit'}), encoding='utf-8')
        try:
            fixture.wait(timeout=5)
        except subprocess.TimeoutExpired:
            fixture.kill()
            fixture.wait()
    fixture_log.close()
    if restore_foreground and previous_foreground and user32.IsWindow(previous_foreground):
        user32.SetForegroundWindow(previous_foreground)
